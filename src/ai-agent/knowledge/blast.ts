/**
 * 简易关键词搜索（后续可替换为向量检索）
 * 特别处理里程查询（如 "DK289+450"）
 */
export function searchBlastKb(query: string, topK = 3): KbChunk[] {
  const lowerQuery = query.toLowerCase()
  const terms = lowerQuery.split(/[\s,，。？、]+/).filter(Boolean)

  // 提取里程号（铁路里程格式，如 DK289+450 → 289450 米）
  const mileageMatch = lowerQuery.match(/dk?\s*(\d{3})\s*\+?\s*(\d{1,3})?/)
  let mileageMeters: number | null = null
  if (mileageMatch) {
    const km = parseInt(mileageMatch[1], 10)
    const meters = mileageMatch[2] ? parseInt(mileageMatch[2].padEnd(3, '0'), 10) : 0
    mileageMeters = km * 1000 + meters
  }

  const scored = BLAST_KB.map(chunk => {
    let score = 0
    for (const kw of chunk.keywords) {
      for (const term of terms) {
        if (kw.includes(term) || term.includes(kw)) score += 1
      }
    }
    // 标题匹配加分
    for (const term of terms) {
      if (chunk.title.includes(term)) score += 3
    }
    // 内容包含匹配加分
    for (const term of terms) {
      if (term.length >= 2 && chunk.content.includes(term)) score += 2
    }

    // 里程匹配：工段数据强加分
    if (mileageMeters !== null && chunk.id.startsWith('ws-')) {
      const wsMileage = parseInt(chunk.id.replace('ws-', ''), 10)
      const diff = Math.abs(wsMileage - mileageMeters)
      if (diff < 300) {
        score += 50   // 精确命中（±300m）
      } else if (diff < 1500) {
        score += 30   // 邻近工段（±1.5km）
      }
    }

    return { chunk, score }
  })

  return scored
    .filter(s => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, topK)
    .map(s => s.chunk)
}
